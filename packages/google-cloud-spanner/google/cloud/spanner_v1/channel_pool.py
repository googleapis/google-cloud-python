class ChannelPool:
    """Dynamic gRPC Channel Pool for Cloud Spanner.

    Provides capacity management, load-balanced channel selection using Power of
    Two Choices (P2C), caller-owned transaction affinity, warm channel priming
    with SELECT 1 via multiplexed sessions, and debounced scale-down with resilient
    draining.
    """

    def __init__(
        self,
        channel_factory: Optional[Callable[[], Any]] = None,
        options: Optional[ChannelPoolOptions] = None,
        initial_channels: Optional[Sequence[Any]] = None,
        auto_start_background_tasks: bool = True,
    ):
        if options is None:
            options = ChannelPoolOptions()
        else:
            options.validate()
        self.options: ChannelPoolOptions = options
        self._channel_factory = channel_factory
        self._pool_lock = CrossSync._Sync_Impl.Lock()
        self._tasks_lock = threading.Lock()
        self._active_entries: Tuple[ChannelEntry, ...] = ()
        self._draining_entries: Tuple[ChannelEntry, ...] = ()
        self._next_entry_id: int = 1
        self._prime_session: Optional[str] = None
        self._scale_up_event = CrossSync._Sync_Impl.Event()
        self._shutdown_event = CrossSync._Sync_Impl.Event()
        self._last_scale_up_time: Optional[float] = None
        self._consecutive_low_load_checks: int = 0
        self._scale_up_task: Optional[Any] = None
        self._scale_down_task: Optional[Any] = None
        self._is_dynamic: bool = (
            self.options.max_channels is None
            or self.options.min_channels < self.options.max_channels
        )
        self._background_tasks_running: bool = False
        from concurrent.futures import ThreadPoolExecutor

        max_priming_workers = max(4, self.options.max_channels or 10)
        self._sync_executor = ThreadPoolExecutor(
            max_workers=max_priming_workers, thread_name_prefix="spanner-pool-priming"
        )
        self._unary_unary_interceptors: List[Any] = []
        self._unary_stream_interceptors: List[Any] = []
        self._stream_unary_interceptors: List[Any] = []
        self._stream_stream_interceptors: List[Any] = []
        channels = list(initial_channels) if initial_channels else []
        num_initial = self.options.initial_channels or self.options.min_channels
        if not channels and channel_factory is not None:
            for _ in range(num_initial):
                channels.append(channel_factory())
        initial_entries: List[ChannelEntry] = []
        for index, channel in enumerate(channels):
            self._attach_interceptors_to_channel(channel)
            entry_id = self._next_entry_id
            logical_id = index + 1
            self._next_entry_id += 1
            initial_entries.append(ChannelEntry(entry_id, logical_id, channel))
        self._active_entries = tuple(initial_entries)
        if self._is_dynamic and auto_start_background_tasks:
            self._start_background_tasks()

    def _attach_interceptors_to_channel(self, channel: Any) -> None:
        """Shares interceptor lists with physical channel for gRPC duck-typing."""
        for attr in (
            "_unary_unary_interceptors",
            "_unary_stream_interceptors",
            "_stream_unary_interceptors",
            "_stream_stream_interceptors",
        ):
            if hasattr(channel, attr):
                channel_interceptors = getattr(channel, attr)
                pool_interceptors = getattr(self, attr)
                if isinstance(channel_interceptors, list) and channel_interceptors:
                    for interceptor in channel_interceptors:
                        if interceptor not in pool_interceptors:
                            pool_interceptors.append(interceptor)
                setattr(channel, attr, pool_interceptors)

    @classmethod
    def from_channels(
        cls,
        channels: Sequence[Any],
        options: Optional[ChannelPoolOptions] = None,
        channel_factory: Optional[Callable[[], Any]] = None,
        auto_start_background_tasks: bool = False,
    ) -> "ChannelPool":
        """Creates a ChannelPool from pre-initialized channels."""
        if options is None:
            options = ChannelPoolOptions(
                min_channels=len(channels),
                max_channels=len(channels),
                initial_channels=len(channels),
            )
        return cls(
            channel_factory=channel_factory,
            options=options,
            initial_channels=channels,
            auto_start_background_tasks=auto_start_background_tasks,
        )

    @property
    def is_dynamic(self) -> bool:
        """Returns True if this pool is dynamically scaling, False if fixed-size static."""
        return self._is_dynamic

    @property
    def active_channels_count(self) -> int:
        """Returns the number of active channels currently in the pool."""
        return len(self._active_entries)

    @property
    def draining_channels_count(self) -> int:
        """Returns the number of draining channels currently tracked by the pool."""
        return len(self._draining_entries)

    def _start_background_tasks(self) -> None:
        pool_ref = ref(self)
        with self._tasks_lock:
            scale_up_thread = Thread(
                target=self._run_scale_up_worker,
                name="spanner-channel-pool-scale-up",
                args=(pool_ref,),
                daemon=True,
            )
            scale_up_thread.start()
            self._scale_up_task = scale_up_thread
            scale_down_thread = Thread(
                target=self._run_scale_down_monitor,
                name="spanner-channel-pool-scale-down",
                args=(pool_ref,),
                daemon=True,
            )
            scale_down_thread.start()
            self._scale_down_task = scale_down_thread
            self._background_tasks_running = True

    def _ensure_background_tasks(self) -> None:
        if not self._is_dynamic or self._shutdown_event.is_set():
            return
        if self._background_tasks_running:
            return
        scale_up_task = self._scale_up_task
        scale_down_task = self._scale_down_task
        if (
            scale_up_task is not None
            and scale_up_task.is_alive()
            and (scale_down_task is not None)
            and scale_down_task.is_alive()
        ):
            self._background_tasks_running = True
            return
        with self._tasks_lock:
            pool_ref = ref(self)
            if self._scale_up_task is None or not self._scale_up_task.is_alive():
                scale_up_thread = Thread(
                    target=self._run_scale_up_worker,
                    name="spanner-channel-pool-scale-up",
                    args=(pool_ref,),
                    daemon=True,
                )
                scale_up_thread.start()
                self._scale_up_task = scale_up_thread
            if self._scale_down_task is None or not self._scale_down_task.is_alive():
                scale_down_thread = Thread(
                    target=self._run_scale_down_monitor,
                    name="spanner-channel-pool-scale-down",
                    args=(pool_ref,),
                    daemon=True,
                )
                scale_down_thread.start()
                self._scale_down_task = scale_down_thread
            self._background_tasks_running = True

    def set_prime_session(self, session_name: str) -> None:
        """Sets the multiplexed session name used for scale-up priming."""
        with self._pool_lock:
            self._prime_session = session_name
            self._last_scale_up_time = None
        self._signal_scale_up()

    def _signal_scale_up(self) -> None:
        self._scale_up_event.set()

    def _make_lease(
        self, entry: ChannelEntry, require_active: bool = False
    ) -> Optional[ChannelLease]:
        in_flight = entry.try_increment_in_flight(require_active=require_active)
        if not in_flight:
            return None
        if self._is_dynamic and in_flight > self.options.max_rpc_per_channel:
            if not self._scale_up_event.is_set():
                self._signal_scale_up()
        return ChannelLease(entry)

    def pick_channel(self) -> Optional[ChannelLease]:
        """Selects an active channel using Power of Two Choices (P2C)."""
        active = self._active_entries
        if not active:
            return None
        candidate = pick_channel_p2c(active)
        if candidate is None:
            return None
        lease = self._make_lease(candidate, require_active=True)
        if lease is not None:
            return lease
        active = self._active_entries
        for entry in active:
            fallback_lease = self._make_lease(entry, require_active=True)
            if fallback_lease is not None:
                return fallback_lease
        return None

    def resolve_affinity(self, affinity: TransactionAffinity) -> Optional[ChannelLease]:
        """Resolves an affinity handle to a leased channel."""
        attached, current_id = affinity.get_state()
        if attached is not None and current_id == attached.id:
            lease = self._make_lease(
                attached, require_active=not affinity.is_read_write()
            )
            if lease is not None:
                return lease
        if current_id is not None:
            for entry in self._active_entries:
                if entry.id == current_id:
                    lease = self._make_lease(entry, require_active=True)
                    if lease is not None:
                        if affinity.is_read_write():
                            affinity.ensure_rw_guard(entry)
                        return lease
            if affinity.is_read_write():
                draining_entry = self.find_draining_entry(current_id)
                if draining_entry is not None:
                    lease = self._make_lease(draining_entry, require_active=False)
                    if lease is not None:
                        affinity.ensure_rw_guard(draining_entry)
                        return lease
        lease = self.pick_channel()
        if lease is None:
            return None
        pinned_entry = affinity.repin_if_stale(current_id, lease.entry)
        if pinned_entry is not lease.entry:
            lease.release()
            return self._make_lease(
                pinned_entry, require_active=not affinity.is_read_write()
            )
        return lease

    def find_draining_entry(self, entry_id: int) -> Optional[ChannelEntry]:
        """Finds a draining channel entry by ID if not closed."""
        for entry in self._draining_entries:
            if entry.id == entry_id and (not entry.is_closed()):
                return entry
        return None

    def acquire(self, affinity: Optional[TransactionAffinity] = None) -> ChannelLease:
        """Acquires a channel lease from the pool, honoring transaction affinity."""
        if self._shutdown_event.is_set():
            raise FailedPrecondition("ChannelPool is closed")
        if not self._background_tasks_running and self._is_dynamic:
            self._ensure_background_tasks()
        if affinity is not None:
            lease = self.resolve_affinity(affinity)
            if lease is not None:
                return lease
        lease = self.pick_channel()
        if lease is None:
            if self._shutdown_event.is_set():
                raise FailedPrecondition("ChannelPool is closed")
            raise ServiceUnavailable("No active channels available in ChannelPool")
        return lease

    @staticmethod
    def _run_scale_up_worker(pool_ref: Any) -> None:
        """Background worker loop that handles dynamic scale-up using weak pool reference."""
        try:
            while True:
                pool = pool_ref()
                if pool is None or pool._shutdown_event.is_set():
                    return
                shutdown_event = pool._shutdown_event
                scale_up_event = pool._scale_up_event
                pool = None
                CrossSync._Sync_Impl.event_wait(scale_up_event, timeout=60.0)
                pool = pool_ref()
                if pool is None or pool._shutdown_event.is_set():
                    return
                if not scale_up_event.is_set():
                    pool = None
                    continue
                if pool._last_scale_up_time is not None:
                    elapsed = time.monotonic() - pool._last_scale_up_time
                    remaining = pool.options.scale_up_cooldown_seconds - elapsed
                    if remaining > 0:
                        shutdown_event = pool._shutdown_event
                        pool = None
                        CrossSync._Sync_Impl.event_wait(
                            shutdown_event, timeout=remaining
                        )
                        pool = pool_ref()
                        if pool is None or pool._shutdown_event.is_set():
                            return
                pool._scale_up_event.clear()
                pool._execute_scale_up()
                pool = None
        except Exception:
            try:
                pool = pool_ref()
                if pool is not None and (not pool._shutdown_event.is_set()):
                    pool._background_tasks_running = False
            except Exception:
                pass
            raise

    def _scale_up_worker_loop(self) -> None:
        """Background worker loop that handles dynamic scale-up and parallel channel priming."""
        self._run_scale_up_worker(ref(self))

    def _execute_scale_up(self) -> None:
        """Executes a single scale-up evaluation and dials/primes channels if needed."""
        channels_to_add = 0
        with self._pool_lock:
            current_len = len(self._active_entries)
            if (
                self.options.max_channels is not None
                and current_len >= self.options.max_channels
            ):
                self._last_scale_up_time = time.monotonic()
                return
            total_load = sum((entry.in_flight_rpcs for entry in self._active_entries))
            desired = self.options.desired_channel_count(total_load)
            max_entry_load = max(
                (entry.in_flight_rpcs for entry in self._active_entries), default=0
            )
            if (
                desired <= current_len
                and max_entry_load <= self.options.max_rpc_per_channel
            ):
                return
            if max_entry_load > self.options.max_rpc_per_channel:
                desired = max(desired, current_len + self.options.min_scale_up_step)
            max_to_add_by_percent = max(
                self.options.min_scale_up_step,
                math.ceil(current_len * self.options.max_scale_up_percent / 100.0),
            )
            candidates = [desired - current_len, max_to_add_by_percent]
            if self.options.max_channels is not None:
                candidates.append(self.options.max_channels - current_len)
            channels_to_add = min(candidates)
            promoted = []
            remaining_draining = []
            sorted_draining = sorted(
                self._draining_entries,
                key=lambda entry: (-entry.last_activity, entry.in_flight_rpcs),
            )
            for entry in sorted_draining:
                if len(promoted) < channels_to_add and (not entry.is_closed()):
                    entry.set_state(ChannelState.ACTIVE)
                    promoted.append(entry)
                else:
                    remaining_draining.append(entry)
            if promoted:
                self._active_entries = self._active_entries + tuple(promoted)
                self._draining_entries = tuple(remaining_draining)
                channels_to_add -= len(promoted)
                self._consecutive_low_load_checks = 0
                self._last_scale_up_time = time.monotonic()
            if channels_to_add <= 0:
                return
            if self._channel_factory is None:
                return
            self._consecutive_low_load_checks = 0
            self._last_scale_up_time = time.monotonic()
        partials = [self._dial_prime_and_publish_one for _ in range(channels_to_add)]
        kwargs = {}
        if not CrossSync._Sync_Impl.is_async and self._sync_executor is not None:
            kwargs["sync_executor"] = self._sync_executor
        CrossSync._Sync_Impl.gather_partials(partials, return_exceptions=True, **kwargs)

    def _dial_prime_and_publish_one(self) -> None:
        if self._channel_factory is None or self._shutdown_event.is_set():
            return
        try:
            channel = CrossSync._Sync_Impl.run_if_async(self._channel_factory)
        except Exception:
            return
        self._attach_interceptors_to_channel(channel)
        if self._prime_session is not None:
            primed = self._prime_channel(channel)
            if primed and (not self._shutdown_event.is_set()):
                self._publish_primed_channel(channel)
            else:
                try:
                    CrossSync._Sync_Impl.run_if_async(channel.close)
                except Exception:
                    pass
        else:
            warmed = self._warm_channel(channel)
            if warmed and (not self._shutdown_event.is_set()):
                self._publish_primed_channel(channel)
            else:
                try:
                    CrossSync._Sync_Impl.run_if_async(channel.close)
                except Exception:
                    pass

    def _warm_channel(self, channel: Any) -> bool:
        """Warms a physical channel without a session by ensuring transport readiness."""
        timeout = self.options.prime_timeout_seconds
        try:
            if hasattr(channel, "subscribe") and hasattr(grpc, "channel_ready_future"):
                ready_future = grpc.channel_ready_future(channel)
                try:
                    ready_future.result(timeout=timeout)
                except Exception:
                    ready_future.cancel()
                    raise
            elif hasattr(channel, "get_state"):
                channel.get_state(try_to_connect=True)
            return True
        except Exception as exc:
            _LOGGER.debug("Channel warming failed: %s", exc)
            return False

    def _prime_channel(self, channel: Any) -> bool:
        """Primes a physical channel with a SELECT 1 query via the multiplexed session."""
        if not self._prime_session:
            return False
        database_name = self._prime_session.split("/sessions/")[0]
        metadata = [
            ("google-cloud-resource-prefix", database_name),
            ("x-goog-request-params", f"database={database_name}"),
        ]
        request = ExecuteSqlRequest(session=self._prime_session, sql="SELECT 1")
        timeout = self.options.prime_timeout_seconds
        for attempt in range(self.options.prime_max_attempts):
            try:
                stub = channel.unary_unary(
                    "/google.spanner.v1.Spanner/ExecuteSql",
                    request_serializer=ExecuteSqlRequest.serialize,
                    response_deserializer=ResultSet.deserialize,
                )
                stub(request, timeout=timeout, metadata=metadata)
                return True
            except Exception:
                if attempt + 1 < self.options.prime_max_attempts and (
                    not self._shutdown_event.is_set()
                ):
                    backoff_seconds = min(0.01 * 2**attempt, 1.0)
                    CrossSync._Sync_Impl.event_wait(
                        self._shutdown_event, timeout=backoff_seconds
                    )
        return False

    def _publish_primed_channel(self, channel: Any) -> bool:
        """Publishes a primed channel into active_entries with a unique logical slot."""
        should_close = False
        with self._pool_lock:
            if (
                self.options.max_channels is not None
                and len(self._active_entries) >= self.options.max_channels
                or self._shutdown_event.is_set()
            ):
                should_close = True
            else:
                occupied_slots: Set[int] = set()
                for entry in self._active_entries:
                    occupied_slots.add(entry.logical_channel_id)
                for entry in self._draining_entries:
                    if not entry.is_closed():
                        occupied_slots.add(entry.logical_channel_id)
                logical_slot = 1
                while logical_slot in occupied_slots:
                    logical_slot += 1
                entry_id = self._next_entry_id
                self._next_entry_id += 1
                new_entry = ChannelEntry(entry_id, logical_slot, channel)
                self._active_entries = self._active_entries + (new_entry,)
                return True
        if should_close:
            try:
                CrossSync._Sync_Impl.run_if_async(channel.close)
            except Exception:
                pass
            return False

    @staticmethod
    def _run_scale_down_monitor(pool_ref: Any) -> None:
        """Background periodic monitor evaluating pool load using weak pool reference."""
        try:
            while True:
                pool = pool_ref()
                if pool is None or pool._shutdown_event.is_set():
                    return
                interval = pool.options.scale_down_interval_secs
                shutdown_event = pool._shutdown_event
                pool = None
                CrossSync._Sync_Impl.event_wait(shutdown_event, timeout=interval)
                pool = pool_ref()
                if pool is None or pool._shutdown_event.is_set():
                    return
                pool._execute_scale_down_check()
                pool._sweep_draining_channels()
                pool = None
        except Exception:
            try:
                pool = pool_ref()
                if pool is not None and (not pool._shutdown_event.is_set()):
                    pool._background_tasks_running = False
            except Exception:
                pass
            raise

    def _scale_down_monitor_loop(self) -> None:
        """Background periodic monitor that evaluates pool load and transitions excess channels to draining."""
        self._run_scale_down_monitor(ref(self))

    def _execute_scale_down_check(self) -> None:
        """Evaluates active channel load and transitions idle channels to draining."""
        self._evaluate_scale_down()

    def _evaluate_scale_down(self) -> None:
        """Evaluates active channel load and transitions idle channels to draining."""
        with self._pool_lock:
            if len(self._active_entries) <= self.options.min_channels:
                self._consecutive_low_load_checks = 0
                return
            total_in_flight = sum(
                (entry.in_flight_rpcs for entry in self._active_entries)
            )
            average_load = total_in_flight / len(self._active_entries)
            if average_load >= self.options.min_rpc_per_channel:
                self._consecutive_low_load_checks = 0
                return
            self._consecutive_low_load_checks += 1
            if (
                self._consecutive_low_load_checks
                < self.options.scale_down_consecutive_checks
            ):
                return
            target_channels = max(
                self.options.min_channels,
                math.ceil(total_in_flight / self.options.min_rpc_per_channel),
            )
            excess_channels = len(self._active_entries) - target_channels
            channels_to_remove = min(
                excess_channels,
                self.options.max_remove_channels,
                len(self._active_entries) - self.options.min_channels,
            )
            if channels_to_remove <= 0:
                self._consecutive_low_load_checks = 0
                return
            candidates = sorted(
                list(self._active_entries),
                key=lambda entry: (
                    entry.in_flight_rpcs,
                    entry.active_rw_transactions,
                    -entry.created_at,
                ),
            )
            to_drain = candidates[:channels_to_remove]
            to_drain_set = set(to_drain)
            for entry in to_drain:
                entry.set_state(ChannelState.DRAINING)
            self._draining_entries = self._draining_entries + tuple(to_drain)
            self._active_entries = tuple(
                (entry for entry in self._active_entries if entry not in to_drain_set)
            )
            self._consecutive_low_load_checks = 0

    def _sweep_draining_channels(self) -> None:
        """Sweeps draining pool and closes idle channels whose draining conditions are met."""
        channels_to_close: List[ChannelEntry] = []
        with self._pool_lock:
            remaining_draining: List[ChannelEntry] = []
            for entry in self._draining_entries:
                if entry.try_close_draining(self.options.drain_idle_grace_seconds):
                    channels_to_close.append(entry)
                else:
                    remaining_draining.append(entry)
            self._draining_entries = tuple(remaining_draining)
        for entry in channels_to_close:
            try:
                CrossSync._Sync_Impl.run_if_async(entry.channel.close)
            except Exception:
                pass

    def close(self) -> None:
        """Closes all active and draining channels and terminates background scaling tasks.

        Note: Immediate closure closes all underlying physical channels without
        waiting for active in-flight RPCs to finish. Outstanding in-flight RPCs
        will be cancelled."""
        self._shutdown_event.set()
        self._scale_up_event.set()
        if self._sync_executor is not None:
            self._sync_executor.shutdown(wait=False, cancel_futures=True)
        with self._tasks_lock:
            threads = [
                thread
                for thread in (self._scale_up_task, self._scale_down_task)
                if thread is not None
                and thread.is_alive()
                and (thread is not threading.current_thread())
            ]
            for thread in threads:
                thread.join(timeout=2.0)
        self._background_tasks_running = False
        channels_to_close: List[ChannelEntry] = []
        with self._pool_lock:
            for entry in self._active_entries:
                entry.set_state(ChannelState.CLOSED)
                channels_to_close.append(entry)
            self._active_entries = ()
            for entry in self._draining_entries:
                entry.set_state(ChannelState.CLOSED)
                channels_to_close.append(entry)
            self._draining_entries = ()
        for entry in channels_to_close:
            try:
                CrossSync._Sync_Impl.run_if_async(entry.channel.close)
            except Exception:
                pass

    def __del__(self) -> None:
        try:
            self._shutdown_event.set()
            self._scale_up_event.set()
            if not CrossSync._Sync_Impl.is_async and self._sync_executor is not None:
                self._sync_executor.shutdown(wait=False, cancel_futures=True)
        except Exception:
            pass

    def _resolve_caller_affinity(self, metadata: Any) -> Optional[TransactionAffinity]:
        if metadata:
            if isinstance(metadata, (list, tuple)) and metadata:
                if len(metadata) >= 2:
                    second_to_last = metadata[-2]
                    if (
                        isinstance(second_to_last, tuple)
                        and len(second_to_last) == 2
                        and (second_to_last[0] == "x-goog-spanner-affinity")
                    ):
                        return second_to_last[1]
                last_item = metadata[-1]
                if (
                    isinstance(last_item, tuple)
                    and len(last_item) == 2
                    and (last_item[0] == "x-goog-spanner-affinity")
                ):
                    return last_item[1]
                for item in metadata:
                    if (
                        isinstance(item, tuple)
                        and len(item) == 2
                        and (item[0] == "x-goog-spanner-affinity")
                    ):
                        return item[1]
            elif isinstance(metadata, dict):
                affinity = metadata.get("x-goog-spanner-affinity")
                if affinity is not None:
                    return affinity
        return None

    def _format_request_metadata(
        self, metadata: Any, logical_channel_id: Union[int, str]
    ) -> Tuple[Any, Optional[str]]:
        """Formats request metadata, rewriting request ID channel slot and removing affinity."""
        if metadata is None:
            return (None, None)
        channel_id_string = (
            logical_channel_id
            if isinstance(logical_channel_id, str)
            else str(logical_channel_id)
        )
        found_request_id = None
        needs_rewrite = False
        if isinstance(metadata, dict):
            new_metadata = {}
            for key, value in metadata.items():
                if key == "x-goog-spanner-affinity":
                    needs_rewrite = True
                    continue
                if key == "x-goog-spanner-request-id" and isinstance(value, str):
                    splits = value.split(".", 4)
                    if len(splits) >= 4 and splits[3] != channel_id_string:
                        splits[3] = channel_id_string
                        value = ".".join(splits)
                        needs_rewrite = True
                    found_request_id = value
                new_metadata[key] = value
            if found_request_id is not None and needs_rewrite:
                span = get_current_span()
                if (
                    span is not None
                    and getattr(span, "is_recording", None)
                    and span.is_recording()
                ):
                    span.set_attribute(
                        X_GOOG_SPANNER_REQUEST_ID_SPAN_ATTR, found_request_id
                    )
            return (new_metadata if needs_rewrite else metadata, found_request_id)
        if isinstance(metadata, list):
            new_metadata = []
            for item in metadata:
                if isinstance(item, tuple) and len(item) == 2:
                    key, value = item
                    if key == "x-goog-spanner-affinity":
                        needs_rewrite = True
                        continue
                    if key == "x-goog-spanner-request-id" and isinstance(value, str):
                        splits = value.split(".", 4)
                        if len(splits) >= 4 and splits[3] != channel_id_string:
                            splits[3] = channel_id_string
                            value = ".".join(splits)
                            item = (key, value)
                            needs_rewrite = True
                        found_request_id = value
                    new_metadata.append(item)
                else:
                    new_metadata.append(item)
            if found_request_id is not None and needs_rewrite:
                span = get_current_span()
                if (
                    span is not None
                    and getattr(span, "is_recording", None)
                    and span.is_recording()
                ):
                    span.set_attribute(
                        X_GOOG_SPANNER_REQUEST_ID_SPAN_ATTR, found_request_id
                    )
            return (new_metadata if needs_rewrite else metadata, found_request_id)
        if isinstance(metadata, tuple):
            new_metadata = []
            for item in metadata:
                if isinstance(item, tuple) and len(item) == 2:
                    key, value = item
                    if key == "x-goog-spanner-affinity":
                        needs_rewrite = True
                        continue
                    if key == "x-goog-spanner-request-id" and isinstance(value, str):
                        splits = value.split(".", 4)
                        if len(splits) >= 4 and splits[3] != channel_id_string:
                            splits[3] = channel_id_string
                            value = ".".join(splits)
                            item = (key, value)
                            needs_rewrite = True
                        found_request_id = value
                    new_metadata.append(item)
                else:
                    new_metadata.append(item)
            if found_request_id is not None and needs_rewrite:
                span = get_current_span()
                if (
                    span is not None
                    and getattr(span, "is_recording", None)
                    and span.is_recording()
                ):
                    span.set_attribute(
                        X_GOOG_SPANNER_REQUEST_ID_SPAN_ATTR, found_request_id
                    )
            return (
                tuple(new_metadata) if needs_rewrite else metadata,
                found_request_id,
            )
        return (metadata, found_request_id)

