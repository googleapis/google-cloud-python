def pick_channel_p2c(candidates: Sequence[ChannelEntry]) -> Optional[ChannelEntry]:
    """Selects an active channel using Power of Two Choices (P2C) algorithm."""
    candidate_count = len(candidates)
    if candidate_count == 0:
        return None
    if candidate_count == 1:
        return candidates[0]
    random_index = random.randrange(candidate_count * (candidate_count - 1))
    first_index = random_index // (candidate_count - 1)
    remainder = random_index % (candidate_count - 1)
    second_index = remainder + 1 if remainder >= first_index else remainder
    entry1 = candidates[first_index]
    entry2 = candidates[second_index]
    load1 = entry1._in_flight_rpcs
    load2 = entry2._in_flight_rpcs
    if load1 < load2:
        return entry1
    if load2 < load1:
        return entry2
    active_rw_count_1 = entry1._active_rw_transactions
    active_rw_count_2 = entry2._active_rw_transactions
    if active_rw_count_1 < active_rw_count_2:
        return entry1
    if active_rw_count_2 < active_rw_count_1:
        return entry2
    return entry1


